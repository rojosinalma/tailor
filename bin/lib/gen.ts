/**
 * Writes the generated source files (*.gen.ts) and checks that every component is complete:
 * a spec, a React component, a showcase entry and, where the spec asks for it, an HTML kit script.
 */
import { existsSync } from "node:fs";
import { Glob } from "bun";
import { PACKS } from "../../core/src/packs";
import type { ComponentSpec } from "../../core/src/spec";
import { at, ROOT } from "./paths";

const scan = async (pattern: string): Promise<string[]> =>
  (await Array.fromAsync(new Glob(pattern).scan(ROOT))).sort();

const write = async (path: string, content: string): Promise<void> => {
  const file = Bun.file(at(path));
  if ((await file.exists()) && (await file.text()) === content) return;
  await Bun.write(file, content);
};

const HEADER = "// Generated by bin/lib/gen.ts. Do not edit.\n";

export interface GenResult {
  readonly specs: readonly ComponentSpec[];
  readonly errors: readonly string[];
}

export async function gen(): Promise<GenResult> {
  const errors: string[] = [];

  // Glyphs: the icons that the kits draw themselves, by pack.
  const iconData = (await Bun.file(at("node_modules/@iconify-json/bi/icons.json")).json()) as {
    icons: Record<string, { body: string }>;
  };
  const glyphs = new Map<string, string>();
  const glyphIcons = new Map<string, string>();
  const packGlyphs: Record<string, Record<string, string>> = {};
  /** The sprite id of a glyph: `t-` and its name in kebab case (close → t-close, chevronDown → t-chevron-down). */
  const glyphId = (name: string): string => `t-${name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`;
  for (const file of [
    ...(await scan("core/packs/*/glyphs.json")),
    ...(await scan("core/packs/*/*/glyphs.json")),
  ]) {
    const map = (await Bun.file(at(file)).json()) as Record<string, string>;
    const pack = file.split("/")[2] ?? "core";
    for (const [name, icon] of Object.entries(map)) {
      const body = iconData.icons[icon]?.body;
      if (!body) errors.push(`${file}: no Bootstrap icon named "${icon}"`);
      else if (glyphs.has(name) && glyphs.get(name) !== body)
        errors.push(`${file}: glyph "${name}" is defined twice`);
      else {
        glyphs.set(name, body);
        glyphIcons.set(name, icon);
        packGlyphs[pack] ??= {};
        packGlyphs[pack][glyphId(name)] = icon;
      }
    }
  }
  const sortedGlyphs = [...glyphIcons].sort(([a], [b]) => a.localeCompare(b));
  await write(
    "core/src/glyph-icons.gen.ts",
    `${HEADER}import * as glyph from "./glyphs.gen";

/** The sprite id of each glyph body: the static markup draws a glyph from the sprite by it. */
export const GLYPH_IDS: ReadonlyMap<string, string> = new Map([
${sortedGlyphs.map(([name]) => `  [glyph.${name}, ${JSON.stringify(glyphId(name))}],`).join("\n")}
]);

/** The glyphs of each pack, sprite id to Bootstrap icon: the sprite of an HTML kit project always holds them. */
export const PACK_GLYPHS: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(
      Object.fromEntries(
        Object.entries(packGlyphs)
          .sort(([a], [b]) => a.localeCompare(b))
          .map(([pack, ids]) => [pack, Object.fromEntries(Object.entries(ids).sort())]),
      ),
    )};
`,
  );
  await write(
    "core/src/glyphs.gen.ts",
    `${HEADER}${[...glyphs]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, body]) => `export const ${name} = ${JSON.stringify(body)};`)
      .join("\n")}\n`,
  );

  // Texts: the base table plus the texts that a component brings.
  const texts = new Map<string, string>();
  const textsByPack: Record<string, Record<string, string>> = {};
  for (const file of ["core/src/texts.json", ...(await scan("core/packs/*/*/texts.json"))]) {
    const map = (await Bun.file(at(file)).json()) as Record<string, string>;
    const pack = file.startsWith("core/packs/") ? (file.split("/")[2] ?? "core") : "core";
    const mine = textsByPack[pack] ?? {};
    textsByPack[pack] = mine;
    for (const [key, value] of Object.entries(map)) {
      if (texts.has(key) && texts.get(key) !== value)
        errors.push(`${file}: the text "${key}" is defined twice`);
      else texts.set(key, value);
      mine[key] = value;
    }
  }
  // The HTML kit gives each pack's script only the texts of that pack.
  await write("core/src/texts-by-pack.gen.json", `${JSON.stringify(textsByPack)}\n`);
  await write(
    "core/src/texts.gen.ts",
    `${HEADER}export const TEXTS = ${JSON.stringify(Object.fromEntries([...texts].sort(([a], [b]) => a.localeCompare(b))), null, 2)} as const;\n`,
  );

  // Specs.
  const specFiles = await scan("core/packs/*/*/spec.ts");
  const specs: ComponentSpec[] = [];
  for (const file of specFiles) {
    const spec = ((await import(at(file))) as { default: ComponentSpec }).default;
    const [, , pack, id] = file.split("/");
    if (spec.id !== id) errors.push(`${file}: id "${spec.id}" differs from the folder name "${id}"`);
    if (spec.pack !== pack)
      errors.push(`${file}: pack "${spec.pack}" differs from the folder name "${pack}"`);
    if (!PACKS.some((p) => p.id === spec.pack)) errors.push(`${file}: unknown pack "${spec.pack}"`);
    if (specs.some((s) => s.id === spec.id)) errors.push(`${file}: the id "${spec.id}" is used twice`);
    if (!existsSync(at(`react/src/${pack}/${id}/${id}.tsx`)))
      errors.push(`${spec.id}: no React component react/src/${pack}/${id}/${id}.tsx`);
    if (!existsSync(at(`react/src/${pack}/${id}/examples.tsx`)))
      errors.push(`${spec.id}: no showcase entry react/src/${pack}/${id}/examples.tsx`);
    const script = existsSync(at(`html/src/${pack}/${id}.ts`));
    if (spec.html === "script" && !script)
      errors.push(`${spec.id}: the spec asks for an HTML kit script html/src/${pack}/${id}.ts`);
    if (spec.html !== "script" && script)
      errors.push(`${spec.id}: html/src/${pack}/${id}.ts exists but the spec says html: "${spec.html}"`);
    specs.push(spec);
  }
  await write(
    "core/src/registry.gen.ts",
    `${HEADER}import type { ComponentSpec } from "./spec";\n${specFiles
      .map((f, i) => `import s${i} from "../${f.slice("core/".length, -".ts".length)}";`)
      .join(
        "\n",
      )}\n\nexport const SPECS: readonly ComponentSpec[] = [${specFiles.map((_, i) => `s${i}`).join(", ")}];\n`,
  );

  // React kit: one index per pack.
  const packsWithReact = new Set(specs.map((s) => s.pack));
  for (const pack of packsWithReact) {
    const mine = specs.filter((s) => s.pack === pack);
    await write(
      `react/src/${pack}/index.gen.ts`,
      `${HEADER}${mine.map((s) => `export * from "./${s.id}/${s.id}";`).join("\n")}\n`,
    );
  }

  // HTML kit: one entry per pack that has scripts.
  for (const pack of PACKS) {
    const scripts = specs.filter((s) => s.pack === pack.id && s.html === "script");
    const boot = existsSync(at(`html/src/${pack.id}/boot.ts`));
    if (scripts.length === 0 && !boot) continue;
    await write(
      `html/src/${pack.id}/index.gen.ts`,
      `${HEADER}${boot ? 'import "./boot";\n' : ""}${scripts.map((s) => `import "./${s.id}";`).join("\n")}\n`,
    );
  }

  // Showcase: every example file, loaded on demand.
  await write(
    "showcase/src/examples.gen.ts",
    `${HEADER}import type { ExampleSet } from "@tailor/react/examples";\n\nexport const EXAMPLES: Readonly<Record<string, () => Promise<{ default: ExampleSet }>>> = {\n${specs
      .map((s) => `  ${JSON.stringify(s.id)}: () => import("@tailor/react/${s.pack}/${s.id}/examples"),`)
      .join("\n")}\n};\n`,
  );

  return { specs, errors };
}

if (import.meta.main) {
  const { specs, errors } = await gen();
  for (const e of errors) console.error(`error: ${e}`);
  console.log(`gen: ${specs.length} components${errors.length ? `, ${errors.length} errors` : ""}`);
  if (errors.length) process.exit(1);
}
